marks = float(input  ("Enter your mark : "))

if marks <0 or marks >  100:
    print("Invalid marks")
    
elif marks >= 80:
    print ("Excellent")
    
elif marks >= 60:
    print ("Good")
    
elif marks >= 40:
    print ("Pass")
else:
    print ("Fail")

 

